export function translate(key: keyof typeof translations.vi, lang: Locale, replacements?: Record<string, string | number>): string {
  let text = translations[lang]?.[key] || translations['vi']?.[key] || String(key);
  if (replacements) {
    Object.entries(replacements).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}
